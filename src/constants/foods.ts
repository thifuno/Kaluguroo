export function searchFoods(foods: FoodItem[], query: string): FoodItem[] {
  const q = query.trim().toLowerCase();
  if (!q) return foods;
  return foods.filter(
    (food) =>
      food.name.toLowerCase().includes(q) ||
      food.nameEn.toLowerCase().includes(q) ||
      food.category.includes(q),
  );
}
